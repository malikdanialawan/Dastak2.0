import 'dart:typed_data';

import 'package:flutter/material.dart';

import '../../core/constants.dart';
import '../../core/helpers.dart';
import '../../core/models.dart';
import '../../data/repositories.dart';
import '../../widgets/shared_widgets.dart';

class CreatePassScreen extends StatefulWidget {
  const CreatePassScreen({super.key});

  @override
  State<CreatePassScreen> createState() => _CreatePassScreenState();
}

class _CreatePassScreenState extends State<CreatePassScreen> {
  final _formKey = GlobalKey<FormState>();

  // Controllers
  final _nameController = TextEditingController();
  final _phoneController = TextEditingController();
  final _emailController = TextEditingController();
  final _vehicleController = TextEditingController();
  final _purposeController = TextEditingController();
  final _notesController = TextEditingController();
  final _companyController = TextEditingController();

  // State
  bool _isSaving = false;
  bool _isRecurring = false;
  bool _multipleEntries = false;
  bool _approveAtGate = false;

  String _visitorType = kTypeGuest;
  int _visitorCount = 1;

  // Schedule State (Standard)
  DateTime _validFrom = DateTime.now();
  DateTime _validUntil = DateTime.now().add(const Duration(hours: 6));

  // Schedule State (Recurring)
  final Set<int> _selectedDays = {1, 2, 3, 4, 5}; // Default Mon-Fri
  TimeOfDay _windowStart = const TimeOfDay(hour: 8, minute: 0);
  TimeOfDay _windowEnd = const TimeOfDay(hour: 18, minute: 0);

  // Photo State
  Uint8List? _photoBytes;
  Uint8List? _thumbBytes;

  @override
  void dispose() {
    _nameController.dispose();
    _phoneController.dispose();
    _emailController.dispose();
    _vehicleController.dispose();
    _purposeController.dispose();
    _notesController.dispose();
    _companyController.dispose();
    super.dispose();
  }

  String _formatTimeForDb(TimeOfDay t) {
    return '${t.hour.toString().padLeft(2, '0')}:${t.minute.toString().padLeft(2, '0')}:00';
  }

  Future<void> _pickPhoto({required bool fromCamera}) async {
    try {
      // Get compressed image and thumbnail (V2 Helper)
      final bytes = await pickAndCompressPhoto(
          fromCamera: fromCamera, isThumbnail: false);
      if (bytes == null) return;

      final thumb =
          await pickAndCompressPhoto(fromCamera: fromCamera, isThumbnail: true);

      setState(() {
        _photoBytes = bytes;
        _thumbBytes = thumb;
      });
    } catch (e) {
      if (mounted)
        showSnack(context, 'Failed to process image.', isError: true);
    }
  }

  Future<void> _submit() async {
    if (!_formKey.currentState!.validate()) return;
    if (_isRecurring && _selectedDays.isEmpty) {
      showSnack(
          context, 'Please select at least one day for the recurring pass.',
          isError: true);
      return;
    }
    FocusScope.of(context).unfocus();
    setState(() => _isSaving = true);

    try {
      final profile = await authService.loadProfile();
      if (profile == null || profile.societyId == null) {
        throw const AppException('Profile setup incomplete.');
      }

      final newPass = Pass(
        id: '',
        qrToken: '', // Generated by DB
        visitorName: _nameController.text.trim(),
        visitorPhone: _phoneController.text.trim().isEmpty
            ? null
            : _phoneController.text.trim(),
        visitorEmail: _emailController.text.trim().isEmpty
            ? null
            : _emailController.text.trim(),
        visitorType: _visitorType,
        company: _companyController.text.trim().isEmpty
            ? null
            : _companyController.text.trim(),
        visitorCount: _visitorCount,
        vehicle: _vehicleController.text.trim().isEmpty
            ? null
            : _vehicleController.text.trim(),
        purpose: _purposeController.text.trim().isEmpty
            ? null
            : _purposeController.text.trim(),
        apartment: profile.societyId, // Linked to society
        createdBy: profile.id,
        societyId: profile.societyId,
        kind: PassKind.visitor,
        status: PassStatus.active,

        // Standard schedule
        validFrom: _isRecurring ? null : _validFrom,
        validUntil: _isRecurring ? null : _validUntil,
        multipleEntries: _isRecurring || _multipleEntries,

        // Recurring schedule
        recurrenceDays: _isRecurring ? _selectedDays.toList() : [],
        windowStart: _isRecurring ? _formatTimeForDb(_windowStart) : null,
        windowEnd: _isRecurring ? _formatTimeForDb(_windowEnd) : null,
      );

      await passService.createPass(
        newPass,
        photoBytes: _photoBytes,
        thumbBytes: _thumbBytes,
      );

      if (mounted) {
        Navigator.pop(context, true);
        showSnack(context, 'Pass generated successfully!');
      }
    } catch (e) {
      if (mounted) showSnack(context, errorText(e), isError: true);
    } finally {
      if (mounted) setState(() => _isSaving = false);
    }
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      backgroundColor: AppColors.background,
      appBar: AppBar(
        title: const Text('New Visitor Pass'),
        backgroundColor: AppColors.background,
        elevation: 0,
      ),
      body: SafeArea(
        child: Form(
          key: _formKey,
          child: ListView(
            padding: const EdgeInsets.all(24),
            children: [
              // --- Section 1: Visitor Photo ---
              Center(
                child: GestureDetector(
                  onTap: () => _showPhotoOptions(),
                  child: Container(
                    width: 100,
                    height: 100,
                    decoration: BoxDecoration(
                      color: AppColors.surface,
                      shape: BoxShape.circle,
                      border: Border.all(
                          color: AppColors.primary.withOpacity(0.3), width: 2),
                      image: _photoBytes != null
                          ? DecorationImage(
                              image: MemoryImage(_photoBytes!),
                              fit: BoxFit.cover)
                          : null,
                    ),
                    child: _photoBytes == null
                        ? const Icon(Icons.add_a_photo_rounded,
                            color: AppColors.primary, size: 32)
                        : null,
                  ),
                ),
              ),
              const SizedBox(height: 8),
              Center(
                child: Text(
                  'Add Visitor Photo (Optional)',
                  style: AppTextStyles.bodySmall
                      .copyWith(color: AppColors.textSecondary),
                ),
              ),
              const SizedBox(height: 32),

              // --- Section 2: Visitor Details ---
              const FieldLabel('Visitor Details'),
              TextFormField(
                controller: _nameController,
                decoration: fieldDecoration(
                    label: 'Visitor Name', icon: Icons.person_outline_rounded),
                textCapitalization: TextCapitalization.words,
                validator: (v) => validateRequired(v, 'Visitor name'),
              ),
              const SizedBox(height: 16),

              DropdownButtonFormField<String>(
                value: _visitorType,
                decoration: fieldDecoration(
                    label: 'Visitor Type', icon: Icons.category_outlined),
                items: kVisitorTypes
                    .map((t) => DropdownMenuItem(value: t, child: Text(t)))
                    .toList(),
                onChanged: (val) {
                  setState(() {
                    _visitorType = val!;
                    _companyController.clear();
                  });
                },
              ),
              const SizedBox(height: 16),

              if (kCompaniesFor(_visitorType).isNotEmpty) ...[
                DropdownButtonFormField<String>(
                  value: _companyController.text.isNotEmpty
                      ? _companyController.text
                      : null,
                  decoration: fieldDecoration(
                      label: 'Company', icon: Icons.business_rounded),
                  items: kCompaniesFor(_visitorType)
                      .map((c) => DropdownMenuItem(value: c, child: Text(c)))
                      .toList(),
                  onChanged: (val) =>
                      setState(() => _companyController.text = val ?? ''),
                ),
                const SizedBox(height: 16),
              ],

              Row(
                children: [
                  Expanded(
                    child: TextFormField(
                      controller: _phoneController,
                      decoration: fieldDecoration(
                          label: 'Phone (Optional)',
                          icon: Icons.phone_outlined),
                      keyboardType: TextInputType.phone,
                      validator: validatePhoneOptional,
                    ),
                  ),
                  const SizedBox(width: 12),
                  Expanded(
                    child: TextFormField(
                      controller: _vehicleController,
                      decoration: fieldDecoration(
                          label: 'Vehicle (Optional)',
                          icon: Icons.directions_car_outlined),
                    ),
                  ),
                ],
              ),
              const SizedBox(height: 24),

              // --- Section 3: Schedule ---
              const FieldLabel('Schedule'),
              Container(
                padding: const EdgeInsets.all(16),
                decoration: BoxDecoration(
                  color: AppColors.surface,
                  borderRadius: BorderRadius.circular(16),
                  border: Border.all(color: AppColors.surfaceMuted),
                ),
                child: Column(
                  children: [
                    Row(
                      mainAxisAlignment: MainAxisAlignment.spaceBetween,
                      children: [
                        Row(
                          children: [
                            const Icon(Icons.repeat_rounded,
                                color: AppColors.primary),
                            const SizedBox(width: 12),
                            Column(
                              crossAxisAlignment: CrossAxisAlignment.start,
                              children: [
                                Text('Recurring Pass',
                                    style: AppTextStyles.bodyLarge
                                        .copyWith(fontWeight: FontWeight.bold)),
                                Text('For maids, drivers, or tutors',
                                    style: AppTextStyles.bodySmall),
                              ],
                            ),
                          ],
                        ),
                        Switch(
                          value: _isRecurring,
                          activeColor: AppColors.primary,
                          onChanged: (val) =>
                              setState(() => _isRecurring = val),
                        ),
                      ],
                    ),
                    if (_isRecurring) ...[
                      const Divider(height: 32),
                      Align(
                        alignment: Alignment.centerLeft,
                        child: Text('Active Days', style: AppTextStyles.label),
                      ),
                      const SizedBox(height: 12),
                      Wrap(
                        spacing: 8,
                        runSpacing: 8,
                        children: kRecurrenceDays.entries.map((e) {
                          final isSelected = _selectedDays.contains(e.key);
                          return GestureDetector(
                            onTap: () {
                              setState(() {
                                if (isSelected) {
                                  _selectedDays.remove(e.key);
                                } else {
                                  _selectedDays.add(e.key);
                                }
                              });
                            },
                            child: Container(
                              width: 44,
                              height: 44,
                              decoration: BoxDecoration(
                                color: isSelected
                                    ? AppColors.primary
                                    : AppColors.background,
                                shape: BoxShape.circle,
                                border: Border.all(
                                    color: isSelected
                                        ? AppColors.primary
                                        : AppColors.surfaceMuted),
                              ),
                              child: Center(
                                child: Text(
                                  e.value[0],
                                  style: AppTextStyles.bodyMedium.copyWith(
                                    color: isSelected
                                        ? Colors.white
                                        : AppColors.textSecondary,
                                    fontWeight: isSelected
                                        ? FontWeight.bold
                                        : FontWeight.normal,
                                  ),
                                ),
                              ),
                            ),
                          );
                        }).toList(),
                      ),
                      const SizedBox(height: 16),
                      Row(
                        children: [
                          Expanded(
                            child: _buildTimePicker(
                              label: 'Start Time',
                              time: _windowStart,
                              onChanged: (t) =>
                                  setState(() => _windowStart = t),
                            ),
                          ),
                          const SizedBox(width: 12),
                          Expanded(
                            child: _buildTimePicker(
                              label: 'End Time',
                              time: _windowEnd,
                              onChanged: (t) => setState(() => _windowEnd = t),
                            ),
                          ),
                        ],
                      ),
                    ] else ...[
                      const Divider(height: 32),
                      Row(
                        children: [
                          Expanded(
                            child: _buildDateTimePicker(
                              label: 'Valid From',
                              date: _validFrom,
                              onChanged: (d) => setState(() => _validFrom = d),
                            ),
                          ),
                          const SizedBox(width: 12),
                          Expanded(
                            child: _buildDateTimePicker(
                              label: 'Valid Until',
                              date: _validUntil,
                              onChanged: (d) => setState(() => _validUntil = d),
                            ),
                          ),
                        ],
                      ),
                    ],
                  ],
                ),
              ),
              const SizedBox(height: 24),

              // --- Section 4: Rules ---
              const FieldLabel('Rules & Notes'),
              SwitchListTile(
                contentPadding: EdgeInsets.zero,
                title: const Text('Approve at gate'),
                subtitle:
                    const Text('Guard will call you before letting them in'),
                value: _approveAtGate,
                activeColor: AppColors.primary,
                onChanged: (v) => setState(() => _approveAtGate = v),
              ),
              if (!_isRecurring)
                SwitchListTile(
                  contentPadding: EdgeInsets.zero,
                  title: const Text('Allow multiple entries'),
                  subtitle: const Text('Pass stays valid for repeat entry'),
                  value: _multipleEntries,
                  activeColor: AppColors.primary,
                  onChanged: (v) => setState(() => _multipleEntries = v),
                ),
              const SizedBox(height: 12),
              TextFormField(
                controller: _notesController,
                maxLines: 3,
                decoration: fieldDecoration(
                  label: 'Notes for guard (Optional)',
                  icon: Icons.notes_rounded,
                ),
              ),

              const SizedBox(height: 40),

              // --- Submit ---
              AppButton(
                label: 'Generate Pass',
                icon: Icons.qr_code_2_rounded,
                isLoading: _isSaving,
                onPressed: _submit,
              ),
              const SizedBox(height: 24),
            ],
          ),
        ),
      ),
    );
  }

  // ==========================================================================
  // HELPER WIDGETS
  // ==========================================================================

  Widget _buildTimePicker({
    required String label,
    required TimeOfDay time,
    required Function(TimeOfDay) onChanged,
  }) {
    return InkWell(
      onTap: () async {
        final t = await showTimePicker(context: context, initialTime: time);
        if (t != null) onChanged(t);
      },
      child: Container(
        padding: const EdgeInsets.all(16),
        decoration: BoxDecoration(
          color: AppColors.background,
          borderRadius: BorderRadius.circular(12),
        ),
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            Text(label, style: AppTextStyles.label),
            const SizedBox(height: 4),
            Text(time.format(context),
                style: AppTextStyles.bodyLarge
                    .copyWith(fontWeight: FontWeight.bold)),
          ],
        ),
      ),
    );
  }

  Widget _buildDateTimePicker({
    required String label,
    required DateTime date,
    required Function(DateTime) onChanged,
  }) {
    return InkWell(
      onTap: () async {
        final d = await pickDateTime(context, initial: date);
        if (d != null) onChanged(d);
      },
      child: Container(
        padding: const EdgeInsets.all(16),
        decoration: BoxDecoration(
          color: AppColors.background,
          borderRadius: BorderRadius.circular(12),
        ),
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            Text(label, style: AppTextStyles.label),
            const SizedBox(height: 4),
            Text(
              '${date.day}/${date.month} ${formatTime(date)}',
              style: AppTextStyles.bodyMedium
                  .copyWith(fontWeight: FontWeight.bold),
            ),
          ],
        ),
      ),
    );
  }

  void _showPhotoOptions() {
    showModalBottomSheet(
      context: context,
      backgroundColor: AppColors.background,
      shape: const RoundedRectangleBorder(
          borderRadius: BorderRadius.vertical(top: Radius.circular(24))),
      builder: (ctx) => SafeArea(
        child: Column(
          mainAxisSize: MainAxisSize.min,
          children: [
            const SizedBox(height: 16),
            ListTile(
              leading: const Icon(Icons.camera_alt_rounded,
                  color: AppColors.primary),
              title: const Text('Take Photo'),
              onTap: () {
                Navigator.pop(ctx);
                _pickPhoto(fromCamera: true);
              },
            ),
            ListTile(
              leading: const Icon(Icons.photo_library_rounded,
                  color: AppColors.primary),
              title: const Text('Choose from Gallery'),
              onTap: () {
                Navigator.pop(ctx);
                _pickPhoto(fromCamera: false);
              },
            ),
            if (_photoBytes != null)
              ListTile(
                leading:
                    const Icon(Icons.delete_rounded, color: AppColors.danger),
                title: const Text('Remove Photo',
                    style: TextStyle(color: AppColors.danger)),
                onTap: () {
                  Navigator.pop(ctx);
                  setState(() {
                    _photoBytes = null;
                    _thumbBytes = null;
                  });
                },
              ),
            const SizedBox(height: 16),
          ],
        ),
      ),
    );
  }
}
